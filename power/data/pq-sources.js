// ソースのステップ（Excel の日本語版が作るのと同じ書き方）
export const sourceStep = name => PQ_FILES[name]
  ? `Csv.Document(File.Contents("C:\\データ\\${name}"),[Delimiter=",", Columns=5, Encoding=65001, QuoteStyle=QuoteStyle.Csv])`
  : `Excel.CurrentWorkbook(){[Name="${name}"]}[Content]`;

const TYPE_M = { int: 'Int64.Type', text: 'type text', date: 'type date', number: 'type number', currency: 'Currency.Type', logical: 'type logical' };
export const typeStepSrc = (prev, types) => `Table.TransformColumnTypes(${prev},{${Object.entries(types).map(([c, t]) => `{"${c}", ${TYPE_M[t] || 'type any'}}`).join(', ')}})`;
// 補助クエリ（演習で参照するだけのクエリ）は「ソース → 変更された型」の2ステップ
export const helperQuery = name => `let\n    ソース = ${sourceStep(name)},\n    #"変更された型" = ${typeStepSrc('ソース', PQ_SOURCES[name].types)}\nin\n    #"変更された型"`;
